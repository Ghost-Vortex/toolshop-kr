/**
 * Категории (роли) клиентов приложения.
 * Используются в декораторе @Roles() и в RolesGuard для разграничения доступа.
 */
export enum Role {
  /** Администратор: полный доступ, включая управление пользователями */
  Admin = 'admin',
  /** Менеджер: управление каталогом и обработка заказов */
  Manager = 'manager',
  /** Покупатель: оформление заказов и отзывы */
  Customer = 'customer',
}
